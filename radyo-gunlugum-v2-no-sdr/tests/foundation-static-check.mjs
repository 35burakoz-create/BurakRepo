check('Runtime Core owns load/show/render',runtime.includes('R.load=async')&&runtime.includes('R.show=u=>')&&runtime.includes('R.renderAll=')&&runtime.includes("provider:'app-runtime-core'"));
check('Router Core uses pristine core switch',router.includes('R.coreSwitch')&&router.includes("provider:'app-router-core'"));
